//! The IPTC field table: one static list drives the sidebar form, the
//! template editor and the exiftool tag mapping.
//!
//! Each row names a stable id (also the key stored in a template's
//! `fields_json`), the label, the group, the widget kind and the exiftool
//! tags to read and write. Writes go to every tag of a row (XMP first, then
//! the IIM twin where one exists), the same dual-write convention the
//! template writer uses. Reads take the first tag that has a value.
//!
//! Correcting the list later means editing [`FIELDS`] only.
//!
//! Out of scope: the repeating structures (Locations shown, Artwork or
//! object, Registry entries).

/// Form section a field belongs to.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub enum Group {
    Description,
    CreatorRights,
    Job,
    Location,
    Contact,
    ImageRights,
}

impl Group {
    pub const ALL: [Group; 6] = [
        Group::Description,
        Group::CreatorRights,
        Group::Job,
        Group::Location,
        Group::Contact,
        Group::ImageRights,
    ];

    pub fn label(self) -> &'static str {
        match self {
            Group::Description => "Description",
            Group::CreatorRights => "Creator and rights",
            Group::Job => "Job",
            Group::Location => "Location",
            Group::Contact => "Creator contact",
            Group::ImageRights => "Image rights and release",
        }
    }

    /// Sections that start expanded.
    pub fn open_by_default(self) -> bool {
        matches!(self, Group::Description | Group::CreatorRights)
    }
}

/// Widget kind of a field.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Kind {
    Single,
    /// Multi-line text with the visible row count.
    Multi(usize),
    /// `;`-separated values, written as a list.
    List,
    /// `YYYY-MM-DD`.
    Date,
    /// Fixed choices as `(label, value)`; the empty value means not set.
    Select(&'static [(&'static str, &'static str)]),
    CountryCode,
}

/// One row of the table.
#[derive(Clone, Copy, Debug)]
pub struct FieldSpec {
    pub id: &'static str,
    pub label: &'static str,
    pub group: Group,
    pub kind: Kind,
    /// XMP tags (`XMP-dc:Title`), written and read first.
    pub xmp: &'static [&'static str],
    /// IIM twin tags (`IPTC:ObjectName`); empty when there is none.
    pub iim: &'static [&'static str],
}

impl FieldSpec {
    /// Every tag of the row, XMP first.
    pub fn tags(&self) -> impl Iterator<Item = &'static str> + use<> {
        self.xmp.iter().chain(self.iim.iter()).copied()
    }

    pub fn is_list(&self) -> bool {
        self.kind == Kind::List
    }
}

