/// Look a row up by id.
pub fn field(id: &str) -> Option<&'static FieldSpec> {
    FIELDS.iter().find(|f| f.id == id)
}

/// Rows of one group, in table order.
pub fn group_fields(group: Group) -> impl Iterator<Item = &'static FieldSpec> {
    FIELDS.iter().filter(move |f| f.group == group)
}

/// Normalize a value read from exiftool to the form text: dates become
/// `YYYY-MM-DD`, everything else is kept.
pub fn normalize_read(spec: &FieldSpec, raw: &str) -> String {
    match spec.kind {
        Kind::Date => {
            let day = raw.split([' ', 'T']).next().unwrap_or(raw);
            day.replace(':', "-")
        }
        _ => raw.to_owned(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::HashSet;

    #[test]
    fn ids_are_unique_and_tags_present() {
        let mut seen = HashSet::new();
        for f in FIELDS {
            assert!(seen.insert(f.id), "duplicate id {}", f.id);
            assert!(f.tags().next().is_some(), "{} has no tags", f.id);
            assert!(f.xmp.iter().all(|t| t.starts_with("XMP-")), "{}", f.id);
            assert!(f.iim.iter().all(|t| t.starts_with("IPTC:")), "{}", f.id);
        }
    }

    #[test]
    fn every_group_has_fields_in_order() {
        for g in Group::ALL {
            assert!(group_fields(g).count() > 0, "{g:?} is empty");
        }
        assert_eq!(FIELDS.len(), 49);
    }

    #[test]
    fn selects_have_a_not_set_choice() {
        for f in FIELDS {
            if let Kind::Select(options) = f.kind {
                assert!(options.iter().any(|(_, v)| v.is_empty()), "{}", f.id);
            }
        }
    }

    #[test]
    fn dates_normalize() {
        let spec = field("date_created").unwrap();
        assert_eq!(normalize_read(spec, "2024:01:02"), "2024-01-02");
        assert_eq!(normalize_read(spec, "2024:01:02 10:00:00"), "2024-01-02");
    }

    #[test]
    fn digital_source_urls_share_a_prefix() {
        for (_, v) in DIGITAL_SOURCE_TYPE.iter().filter(|(_, v)| !v.is_empty()) {
            assert!(v.starts_with("http://cv.iptc.org/newscodes/digitalsourcetype/"));
        }
    }
}
