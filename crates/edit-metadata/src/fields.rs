macro_rules! field {
    ($id:literal, $label:literal, $group:ident, $kind:expr, [$($xmp:literal),*], [$($iim:literal),*]) => {
        FieldSpec {
            id: $id,
            label: $label,
            group: Group::$group,
            kind: $kind,
            xmp: &[$($xmp),*],
            iim: &[$($iim),*],
        }
    };
}

